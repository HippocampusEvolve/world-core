/**
 * generators.ts — сами материалы.
 *
 * Перенесены из эталона `demo/cabin-fireplace.html` один в один по замыслу, но
 * не буква в букву по числам: почти каждый второй вызов шума в эталоне нарушал
 * договор о периоде (см. `noise.ts`), и карта не стыковалась сама с собой. В
 * тёмной хижине это не читалось - шов на стене выглядел ещё одним пятном
 * копоти. Здесь множители приведены к целым (для `|sin|` - к кратным половине,
 * у него период π, а не 2π), индексы ячеек заведены через `wrapi`, а
 * доказывает починку не глаз, а замер шва в `test/check.mjs`.
 *
 * Правки, которые изменили картинку, перечислены поимённо в README - молча
 * подкрученных чисел здесь нет.
 *
 * Все генераторы пишут в один и тот же `Px` (см. `bake.ts`): ни одного нового
 * объекта на пиксель.
 */

import { fbm, hash2, ridge, worley, wrapi } from './noise.js'
import { add, cl01, mix, ss, type RGB } from './shape.js'
import type { Generator, Px } from './bake.js'

const TAU = Math.PI * 2

/* ------------------------------------------------------------------ *
 * 1. Бревно сруба - продольная свиль, трещины усушки, потемневшее дерево
 * ------------------------------------------------------------------ */
export const log: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S // v - вдоль бревна
  const swirl = fbm(u * 5, v * 1, 5, 1, 3, 71)
  // 3.5, а не 3.4: у |sin| период π, поэтому целым должно быть удвоенное число оборотов.
  const grain = Math.abs(Math.sin((u * 3.5 + swirl * 2.6) * TAU))
  const fine = fbm(u * 26, v * 4, 26, 4, 4, 131)
  let c: RGB = mix([38, 28, 20], [96, 70, 46], cl01(grain * 0.5 + fine * 0.5))

  // трещины усушки вдоль волокна
  const crack = ss(0.955, 1, ridge(u * 22, v * 2, 22, 2, 3, 191))
  c = mix(c, [16, 11, 8], crack * 0.9)

  // сучки
  const w = worley(u * 4, v * 3, 4, 3, 233)
  const knot = ss(0.22, 0.04, w.f1) * ss(0.72, 0.95, w.id)
  c = mix(c, [30, 20, 13], knot * 0.85)

  c = add(c, (fine - 0.5) * 16)
  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = 0.5 + (grain - 0.5) * 0.25 + (fine - 0.5) * 0.35 - crack * 0.55 - knot * 0.2
  p.rough = 0.86 + (fine - 0.5) * 0.1 - knot * 0.12
}

/* ------------------------------------------------------------------ *
 * 2. Бутовый камень - Worley с искажением домена
 *
 * Разность `f2 - f1` даёт шов между ячейками, из него и растёт кладка. Тон
 * каждого камня берётся из `id` ячейки: без этого соседние блоки выходят
 * одного цвета, и стена читается как штукатурка с прожилками.
 * ------------------------------------------------------------------ */
export function rubble(warm: boolean): Generator {
  const A: RGB = warm ? [72, 68, 62] : [56, 57, 55]
  const B: RGB = warm ? [140, 134, 122] : [116, 118, 114]
  return (x, y, S, p) => {
    const u = x / S
    const v = y / S
    const wx = fbm(u * 6, v * 6, 6, 6, 3, 311) - 0.5
    const wy = fbm(u * 6, v * 6, 6, 6, 3, 317) - 0.5
    // камни вытянуты по горизонтали: пять ячеек поперёк, три вдоль
    const w = worley(u * 5 + wx * 0.55, v * 3 + wy * 0.55, 5, 3, 353)
    const edge = w.f2 - w.f1
    const stone = ss(0.02, 0.13, edge)
    const rock = fbm(u * 70, v * 70, 70, 70, 4, 401)
    let c: RGB = mix(A, B, cl01(w.id * 0.8 + 0.1))
    c = add(c, (rock - 0.5) * 30)

    // сколы и вкрапления
    const pit = ss(0.68, 0.92, fbm(u * 26, v * 26, 26, 26, 3, 433))
    c = mix(c, mix(A, B, 0.15), pit * 0.4)
    const spar = ss(0.86, 1, fbm(u * 120, v * 120, 120, 120, 2, 461))
    c = mix(c, [186, 182, 172], spar * 0.5)

    // раствор
    const mortar = 1 - stone
    c = mix(c, [46, 44, 41], mortar * 0.88)

    p.r = c[0]
    p.g = c[1]
    p.b = c[2]
    p.h = stone * 0.72 + 0.12 + (rock - 0.5) * 0.2 - pit * 0.1
    p.rough = 0.9 - stone * 0.06 + pit * 0.05
  }
}

/* ------------------------------------------------------------------ *
 * 3. Плиты пода - крупная неровная брусчатка, светлее и теплее бута
 * ------------------------------------------------------------------ */
export const hearth: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const wx = (fbm(u * 8, v * 8, 8, 8, 3, 503) - 0.5) * 0.35
  const w = worley(u * 3 + wx, v * 3 - wx, 3, 3, 541)
  const edge = ss(0.015, 0.1, w.f2 - w.f1)
  const rock = fbm(u * 60, v * 60, 60, 60, 4, 577)
  let c: RGB = mix([104, 96, 84], [172, 160, 140], cl01(w.id * 0.85 + 0.08))
  c = add(c, (rock - 0.5) * 26)
  const soot = ss(0.55, 0.9, fbm(u * 5, v * 5, 5, 5, 4, 601))
  c = mix(c, [48, 42, 38], soot * 0.45)
  c = mix(c, [62, 57, 50], (1 - edge) * 0.85)
  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = edge * 0.68 + 0.14 + (rock - 0.5) * 0.22
  p.rough = 0.86 - edge * 0.08 + soot * 0.06
}

/* ------------------------------------------------------------------ *
 * 4. Огнеупорный кирпич топки
 *
 * `sootRise` - насколько сажа густеет кверху. В эталоне градиент был вшит
 * намертво (значение 1), и карта из-за него не стыковалась по вертикали: у
 * монотонного градиента верх с низом не сходится по определению. Для топки
 * высотой в один тайл это правильно, для стены в два - уже нет, поэтому
 * градиент стал ручкой. На нуле кирпич тайлится в обе стороны; это проверено
 * счётом, а не обещано.
 *
 * Рядов ЧЁТНОЕ число, и это не вкусовщина: перевязка сдвигает каждый второй ряд
 * на полкирпича, и при нечётном числе на стыке тайлов встают два ряда с
 * одинаковым сдвигом - швы выстраиваются в столбик ровно там, где кладка должна
 * выглядеть непрерывной. В эталоне рядов было девять.
 * ------------------------------------------------------------------ */
export function firebrick(sootRise = 1): Generator {
  const cols = 4
  const rows = 8
  return (x, y, S, p) => {
    const u = x / S
    const v = y / S
    const row = wrapi(Math.floor(v * rows), rows)
    const cu = u * cols + (row % 2) * 0.5
    const col = wrapi(Math.floor(cu), cols)
    const fx = cu - Math.floor(cu)
    const fy = v * rows - Math.floor(v * rows)
    const mx = 3.4 / (S / cols)
    const my = 3.4 / (S / rows)
    const inside = Math.min(ss(0, mx, Math.min(fx, 1 - fx)), ss(0, my, Math.min(fy, 1 - fy)))
    const rnd = hash2(col, row, 653)
    let c: RGB = mix([104, 52, 32], [166, 92, 52], rnd)
    const gr = fbm(u * 80, v * 80, 80, 80, 3, 691)
    c = add(c, (gr - 0.5) * 26)
    c = mix(c, [96, 78, 66], (1 - inside) * 0.8)

    // сажа: пятнами всегда, кверху гуще - по желанию
    const blotch = ss(0.35, 0.8, fbm(u * 7, v * 7, 7, 7, 4, 719))
    const rise = sootRise > 0 ? ss(0.1, 0.75, 1 - v) * sootRise + (1 - sootRise) : 1
    c = mix(c, [26, 21, 19], blotch * rise * 0.85)

    p.r = c[0]
    p.g = c[1]
    p.b = c[2]
    p.h = inside * 0.7 + 0.15 + (gr - 0.5) * 0.2
    p.rough = 0.9 + (gr - 0.5) * 0.08
  }
}

/* ------------------------------------------------------------------ *
 * 5. Половая доска - широкая, тёмная, истёртая
 * ------------------------------------------------------------------ */
export const floor: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const planks = 4
  const pu = u * planks
  const pi = wrapi(Math.floor(pu), planks)
  const f = pu - Math.floor(pu)
  const rnd = hash2(pi, 0, 733)
  const gap = 3.6 / (S / planks)
  const edge = ss(0, gap, Math.min(f, 1 - f))
  const warp = fbm(u * 5, v * 2, 5, 2, 3, 761)
  const rings = Math.abs(Math.sin((f * 5 + warp * 3 + rnd * 5) * TAU))
  const t = cl01(rings * 0.5 + fbm(u * 34, v * 6, 34, 6, 3, 787) * 0.5)
  let c: RGB = mix([44, 33, 24], [104, 80, 55], cl01(t * 0.8 + (rnd - 0.5) * 0.45))
  c = add(c, (fbm(u * 90, v * 9, 90, 9, 3, 809) - 0.5) * 20)

  // вытертые дорожки
  const worn = ss(0.55, 0.95, fbm(u * 3, v * 3, 3, 3, 3, 821))
  c = mix(c, [128, 102, 72], worn * 0.3)

  // поперечные стыки досок: у |sin| период π, три оборота укладываются ровно
  const seg = ss(0.985, 1, Math.abs(Math.sin(v * Math.PI * 3 + rnd * 6)))
  c = mix(c, [22, 16, 11], seg * 0.8)
  c = mix(c, [18, 13, 9], (1 - edge) * 0.92)

  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = edge * 0.62 + 0.18 + (t - 0.5) * 0.2 - seg * 0.4
  p.rough = 0.84 + (1 - edge) * 0.12 - worn * 0.18
}

/* ------------------------------------------------------------------ *
 * 6. Тёсаный брус - следы топора
 * ------------------------------------------------------------------ */
export const beam: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const warp = fbm(u * 3, v * 1, 3, 1, 3, 853)
  const grain = Math.abs(Math.sin((v * 3 + warp * 2.4) * TAU))
  const fine = fbm(u * 8, v * 30, 8, 30, 4, 877)
  let c: RGB = mix([74, 52, 32], [166, 128, 84], cl01(grain * 0.42 + fine * 0.58))

  // затёсы топором - широкие плавные фаски вдоль бруса
  const chop = Math.abs(Math.sin(u * Math.PI * 7 + fbm(u * 4, v * 4, 4, 4, 2, 883) * 4))
  c = add(c, (chop - 0.5) * 22)
  const crack = ss(0.965, 1, ridge(u * 3, v * 16, 3, 16, 3, 907))
  c = mix(c, [26, 18, 12], crack * 0.85)

  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = 0.45 + (chop - 0.5) * 0.4 + (fine - 0.5) * 0.25 - crack * 0.5
  p.rough = 0.85 + (fine - 0.5) * 0.1
}

/* ------------------------------------------------------------------ *
 * 7. Кора поленницы
 * ------------------------------------------------------------------ */
export const bark: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const rid = ridge(u * 16, v * 2, 16, 2, 4, 941)
  const fine = fbm(u * 60, v * 12, 60, 12, 3, 967)
  let c: RGB = mix([32, 26, 20], [96, 84, 62], cl01(rid * 0.72 + fine * 0.38))
  const deep = ss(0.55, 0.95, rid)
  c = mix(c, [18, 14, 10], (1 - deep) * 0.45)
  const moss = ss(0.72, 0.95, fbm(u * 6, v * 6, 6, 6, 3, 983))
  c = mix(c, [72, 82, 48], moss * 0.3)
  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = rid * 0.8 + (fine - 0.5) * 0.25
  p.rough = 0.93 + (fine - 0.5) * 0.06
}

/* ------------------------------------------------------------------ *
 * 8. Торец полена - годовые кольца и радиальные трещины
 *
 * Единственный набор, который не тайлится и не должен: рисунок радиальный, у
 * него есть середина. Он кладётся на торцевую грань цилиндра целиком, одним
 * куском, и повторять его по кромке нечем.
 * ------------------------------------------------------------------ */
export const logEnd: Generator = (x, y, S, p) => {
  const u = x / S - 0.5
  const v = y / S - 0.5
  const r = Math.sqrt(u * u + v * v) * 2 // 0..1 к краю
  const a = Math.atan2(v, u)
  const wob = (fbm(u * 6 + 3, v * 6 + 3, 12, 12, 3, 1009) - 0.5) * 0.1
  const rings = Math.abs(Math.sin((r * 1.0 + wob) * Math.PI * 26))
  let c: RGB = mix([150, 118, 80], [196, 166, 122], cl01(rings * 0.55 + 0.25))

  // сердцевина темнее, заболонь светлее
  c = mix(c, [118, 88, 58], ss(0.34, 0.02, r) * 0.6)
  c = mix(c, [206, 182, 142], ss(0.72, 0.94, r) * 0.5)

  // радиальные трещины
  const spokes = Math.abs(Math.sin(a * 3.5 + fbm(u * 4 + 5, v * 4 + 5, 8, 8, 2, 1031) * 7))
  const crack = ss(0.985, 1, 1 - spokes) * ss(0.06, 0.5, r) * ss(0.98, 0.7, r)
  c = mix(c, [58, 40, 26], crack * 0.9)

  // кора по кромке
  const barkRim = ss(0.9, 0.99, r)
  c = mix(c, [44, 34, 24], barkRim)
  c = add(c, (fbm(u * 40, v * 40, 40, 40, 3, 1049) - 0.5) * 16)

  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = 0.55 + (rings - 0.5) * 0.22 - crack * 0.6 - barkRim * 0.25
  p.rough = 0.82 + barkRim * 0.12
}

/* ------------------------------------------------------------------ *
 * 9. Ткань
 *
 * Переплетение задано числом нитей НА ТАЙЛ, а не шагом в пикселях: в эталоне
 * стояло `sin(u * S * 0.35)`, то есть 14.26 периода на карту 256 - четверть
 * периода не сходилась на стыке. Заодно рисунок перестал зависеть от размера
 * карты: та же ткань на 512 больше не становится вдвое мельче.
 * ------------------------------------------------------------------ */
export const cloth: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const threads = 14
  const weave = (Math.sin(u * TAU * threads) * Math.sin(v * TAU * threads) + 1) * 0.5
  const folds = fbm(u * 4, v * 1, 4, 1, 3, 1093)
  let c: RGB = mix([120, 116, 106], [206, 202, 190], cl01(folds * 0.8 + 0.15))
  c = add(c, (weave - 0.5) * 14)
  const dirt = ss(0.62, 0.95, fbm(u * 7, v * 7, 7, 7, 3, 1103))
  c = mix(c, [116, 104, 86], dirt * 0.35)
  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = folds * 0.7 + weave * 0.3
  p.rough = 0.95
}

/* ------------------------------------------------------------------ *
 * 10. Чугун - единственный, у кого есть карта металла
 *
 * Раковины (`pit`) снимают и металличность, и блеск сразу: ржавая точка не
 * отражает. Ровно поэтому металл здесь картой, а не одним числом на материал.
 * ------------------------------------------------------------------ */
export const iron: Generator = (x, y, S, p) => {
  const u = x / S
  const v = y / S
  const micro = fbm(u * 130, v * 130, 130, 130, 3, 1129)
  let c: RGB = mix([22, 21, 20], [58, 55, 52], cl01(micro))
  const pit = ss(0.7, 0.95, fbm(u * 22, v * 22, 22, 22, 3, 1151))
  c = mix(c, [74, 48, 32], pit * 0.55)
  const hi = ss(0.93, 1, ridge(u * 40, v * 8, 40, 8, 3, 1163))
  c = mix(c, [122, 118, 112], hi * 0.5)
  p.r = c[0]
  p.g = c[1]
  p.b = c[2]
  p.h = 0.5 + (micro - 0.5) * 0.5 - pit * 0.3
  p.rough = 0.52 + pit * 0.35 - hi * 0.2
  p.metal = 0.92 - pit * 0.35
}

/* ------------------------------------------------------------------ *
 * 11. Тёсаная кладка - прямоугольные блоки рядами, сколотые кромки
 *
 * Не замена буту, а другая порода кладки. `rubble` кладёт валуны: Worley с
 * искажением домена, границы органические, раствора много. Здесь камень
 * ОБТЁСАН и уложен рядами с перевязкой - так сложены печные щёки и цоколь, и
 * так выглядит референс, с которого этот рецепт снят.
 *
 * ## Числа сняты с референса, а не выбраны на вкус
 *
 * Референс обмерен по центральным 60 процентам кадра (края у картинки затемнены
 * виньеткой, она утянула бы статистику):
 *
 *     средний цвет  67 54 43      яркость p05/p50/p95  32 / 57 / 76
 *     теплота R−B   24.6          темнее 40 (швы)      12.3%
 *
 * Главное здесь - НЕ палитра, а узкий разброс яркости: от p05 до p95 всего 44
 * байта. Камень почти ровного тона, а весь объём даёт рельеф. Кладка, у которой
 * блоки разной яркости, читается как крашеная фанера: именно этим отличается
 * плохая процедурная стена от хорошей, и именно поэтому тон блока здесь двигает
 * цвет едва-едва, а работает - высота.
 *
 * ## Как ряд делится на блоки и почему он сходится сам с собой
 *
 * В ряду ЦЕЛОЕ число блоков (3..5) - иначе на стыке тайлов встаёт полублок.
 * Ширины при этом разные: координата ряда искажается волной с периодом во весь
 * ряд, `t = τ + a·sin(2π·τ/n)`. Добавка периодична по τ с периодом n, поэтому
 * деление повторяется вместе с тайлом, а блоки выходят разной длины.
 *
 * Амплитуды 0.28 и 0.07 взяты не на глаз: производная `dt/dτ` обязана остаться
 * положительной, иначе искажение перестаёт быть монотонным и блоки начинают
 * налезать друг на друга. При n = 3 это даёт 0.28·2π/3 + 0.07·4π/3 = 0.88 < 1.
 *
 * Перевязка - сдвиг ряда по хешу, а не на полблока: у кладки из тёсаного камня
 * швы не выстраиваются в столбик, но и не расходятся правильной шахматкой.
 *
 * ## Расстояние до шва меряется в долях ТАЙЛА
 *
 * Не в пикселях: тогда шов на карте 1024 стал бы вдвое тоньше, чем на 512 (та
 * же грабля, что была у ткани). При тайле в метр 0.012 - это шов 12 мм.
 * Горизонтальная мера делится на число рядов, вертикальная - на `dt/dτ`, то
 * есть на настоящую ширину блока в этом месте, а не на среднюю.
 * ------------------------------------------------------------------ */
export function ashlar(warm = true): Generator {
  const ROWS = 4
  /** Шов, в долях тайла. */
  const JOINT = 0.009
  /** Фаска по кромке блока - тёсаный камень скруглён не рёбрышком. */
  const BEVEL = 0.022
  const A: RGB = warm ? [40, 32, 24] : [42, 42, 40]
  const B: RGB = warm ? [104, 86, 66] : [96, 96, 93]
  /**
   * Раствор в тени шва. Не чёрный, и это замер, а не вкус: у референса нижние 5
   * процентов яркости лежат на 32, а первый заход давал 18 - шов проваливался в
   * дыру и кладка читалась контуром, как в мультфильме. В тёмном шве всё равно
   * есть свет, просто мало.
   */
  const MORTAR: RGB = warm ? [34, 27, 20] : [35, 35, 33]
  /** Свежий скол по кромке: он всегда светлее выветренной плоскости. */
  const CHIP: RGB = warm ? [128, 110, 86] : [122, 121, 117]

  /*
   * Раскладка рядов и средний тон каждого - один раз на генератор.
   *
   * Средние здесь не для скорости, а против ПОЛОСАТОСТИ, и нашла её проверка, а
   * не глаз: сильнейшей гармоникой профиля яркости оказалась вторая, хотя рядов
   * четыре. Причина арифметическая - в ряду всего 3..5 блоков, и когда тон
   * каждого берётся независимым хешем, средняя яркость РЯДА гуляет сама по
   * себе. Стена начинает читаться широкими полосами поперёк, и это ровно та
   * подделка, которой в референсе нет.
   *
   * Лечение прямое: тон блока отсчитывается от среднего по своему ряду. Камни в
   * ряду остаются разными, ряд от ряда - одинаковым. Так оно и в жизни: камень
   * подбирали по месту, а не меняли породу через каждые тридцать сантиметров.
   */
  const rowBlocks = new Int32Array(ROWS)
  const meanTone = new Float64Array(ROWS)
  const meanWear = new Float64Array(ROWS)
  for (let r = 0; r < ROWS; r++) {
    const n = 3 + Math.floor(hash2(r, 0, 1277) * 3)
    rowBlocks[r] = n
    let a = 0
    let b = 0
    for (let i = 0; i < n; i++) {
      a += hash2(i, r, 1301)
      b += hash2(i, r, 1303)
    }
    meanTone[r] = a / n
    meanWear[r] = b / n
  }

  return (x, y, S, p) => {
    const u = x / S
    const v = y / S

    // ---- ряд ----
    const rowF = v * ROWS
    const row = wrapi(Math.floor(rowF), ROWS)
    const fy = rowF - Math.floor(rowF)

    // ---- деление ряда на блоки ----
    const n = rowBlocks[row] // 3..5, целое
    const shift = hash2(row, 1, 1279)
    const tau = (u + shift) * n
    const w1 = (tau / n) * TAU
    const w2 = w1 * 2 + shift * 6
    const t = tau + 0.28 * Math.sin(w1) + 0.07 * Math.sin(w2)
    // dt/dτ, дальше домножается на n: производная по u, а не по τ
    const dt = (1 + 0.28 * (TAU / n) * Math.cos(w1) + 0.07 * ((2 * TAU) / n) * Math.cos(w2)) * n
    const bi = wrapi(Math.floor(t), n)
    const fx = t - Math.floor(t)

    // ---- подшов: часть блоков расколота надвое ----
    // Мелкие камни между крупными - примета кладки, где блок подгоняли по
    // месту. Решается по индексам блока и ряда, поэтому переживает заворот.
    const sub = hash2(bi, row, 1289)
    let dx = Math.min(fx, 1 - fx) / dt
    let dy = Math.min(fy, 1 - fy) / ROWS
    if (sub > 0.74) dy = Math.min(dy, Math.abs(fy - 0.5) / ROWS)
    else if (sub < 0.16) dx = Math.min(dx, Math.abs(fx - 0.5) / dt)

    // ---- сколотая кромка ----
    // Ровная линия шва выдаёт процедурность мгновенно, поэтому расстояние до
    // края возмущается шумом. Двумя разными, и роли у них разные: мелкий рвёт
    // кромку по всей длине, крупный выкусывает из блока отдельные щербины.
    //
    // Щербина обязана быть РЕДКОЙ. Первый заход брал её порогом 0.62, и она
    // срабатывала почти везде: шов расплывался волнистой лентой в палец
    // толщиной, а кладка читалась как рисунок тушью. Порог 0.82 оставляет её
    // там, где от блока правда отбит угол.
    const chip = (fbm(u * 48, v * 48, 48, 48, 3, 1291) - 0.5) * 0.006
    const bite = ss(0.82, 0.99, ridge(u * 14, v * 14, 14, 14, 3, 1297)) * 0.011
    const d = Math.min(dx, dy) + chip - bite

    // Две ступени, а не один склон: у шва стенка почти отвесная, дальше идёт
    // покатая фаска. Одним smoothstep кладка выходит надувной.
    const rise = ss(0, JOINT * 0.6, d)
    const bev = ss(JOINT * 0.6, JOINT + BEVEL, d)

    // ---- тело камня ----
    // тон и выветренность - ОТ СРЕДНЕГО ПО РЯДУ, см. предпосчёт выше
    const tone = 0.5 + hash2(bi, row, 1301) - meanTone[row]
    const wear = 0.5 + hash2(bi, row, 1303) - meanWear[row]
    // слоистость осадочной породы: медленно по горизонтали, быстро по вертикали
    const lay = fbm(u * 18, v * 72, 18, 72, 4, 1307)
    const gr = fbm(u * 160, v * 160, 160, 160, 3, 1311)
    // Плоские сколы. Берём у клеточного шума не только `id` (тон чешуйки), но
    // и границу `f2 − f1`: без неё чешуйки размазываются пятнами, а камень
    // раскалывается по граням, и грань видно линией.
    //
    // Линия эта должна быть ЕЛЕ ЗАМЕТНОЙ. На полной силе (0.5 в цвете, 0.12 в
    // высоте) по каждому блоку расходилась сетка трещин, и стена читалась как
    // растрескавшаяся глина, а не как тёсаный камень. У референса поверхность
    // блока крупная и плоская; всё, что нужно, - намёк на грань раскола.
    const wf = worley(u * 22, v * 22, 22, 22, 1319)
    const facet = wf.id
    const facetEdge = ss(0.05, 0.008, wf.f2 - wf.f1)
    const pit = ss(0.74, 0.96, fbm(u * 44, v * 44, 44, 44, 3, 1321))
    const crack = ss(0.972, 1, ridge(u * 30, v * 30, 30, 30, 3, 1327))

    let c: RGB = mix(A, B, cl01(0.12 + tone * 0.3 + lay * 0.4 + gr * 0.18))
    c = add(c, (wear - 0.5) * 14)
    c = add(c, (facet - 0.5) * 11)
    c = add(c, (gr - 0.5) * 12)
    c = mix(c, mix(A, B, 0.1), pit * 0.45)
    // грани скола и трещины - только по телу блока, у кромки их съедает фаска
    c = mix(c, A, facetEdge * bev * 0.18)
    c = mix(c, A, crack * bev * 0.35)
    // кромка: свежий скол светлее плоскости
    c = mix(c, CHIP, (1 - bev) * rise * 0.45)
    // и наконец шов
    c = mix(c, MORTAR, 1 - rise)

    p.r = c[0]
    p.g = c[1]
    p.b = c[2]
    p.h =
      0.08 +
      rise * 0.42 +
      bev * 0.16 +
      (tone - 0.5) * 0.05 +
      ((lay - 0.5) * 0.16 - facetEdge * 0.05 - crack * 0.1) * bev +
      (gr - 0.5) * 0.05 -
      pit * 0.12
    p.rough = 0.92 - facet * 0.05 + pit * 0.04
  }
}

